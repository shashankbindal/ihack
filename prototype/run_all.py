def finalize_metrics(cleaning: dict, poi_counts: dict) -> None:
    metrics = load_metrics()
    listing_source = json.loads(ingest_listings.SOURCE_FILE.read_text())
    worst = metrics["subgroup_audit"]["worst_by_mdape"]
    localities = geocode.city_centres()
    resolved = pd.read_parquet(geocode.LOCALITIES_PATH).query("locality != '__centre__'")
    outcomes = resolved.groupby(["city", "geo_precision"]).size().unstack(fill_value=0)
    update_metrics(
        dataset=f"Kaggle {listing_source['dataset']} ({listing_source['licence']}); listing asking prices, "
                f"apartments, snapshot {listing_source['last_updated'][:10]}",
        ground_truth="listing asking price (proxy), not registered transaction value",
        cities=list(config.CITIES),
        n_cities=len(config.CITIES),
        data={**cleaning, "osm_poi_counts": poi_counts,
              "geocoding": "Nominatim, locality centroids; rows whose locality resolved only to a city centroid "
                           "or not at all are dropped",
              "geocoding_outcomes_by_city": {c: {k: int(v) for k, v in row.items()} for c, row in outcomes.iterrows()},
              "city_centres": {c: list(v) for c, v in localities.items()}},
        worst_subgroup={"dimension": worst["dimension"], "group": worst["value"], "mdape": worst["mdape"],
                        "n": worst["n"]},
        interval_width_median=metrics["coverage_80"]["overall"]["median_width_pct"],
        not_run=NOT_RUN,
    )


def write_summary(metrics: dict) -> None:
    """results/summary.md, generated from metrics.json so no number is typed by hand."""
    def model_rows(block: dict) -> list[str]:
        return [f"| {name} | {m['mdape']:.1f} | {m['mape']:.1f} | {m['ppe10']:.1f} | {m['ppe20']:.1f} | "
                f"{m['bias']:+.1f} | {m['overval20']:.1f} |" for name, m in block.items()]

    header = ["| Model | MdAPE | MAPE | PPE10 | PPE20 | Bias | Over-val >20% |", "|---|---|---|---|---|---|---|"]
    coverage = metrics["coverage_80"]
    significance = metrics["significance"]["M+_vs_B2"]
    selected = metrics["routing_curve"]["selected"]
    lines = [
        "# Results summary (generated by run_all.py from metrics.json)", "",
        f"Dataset: {metrics['dataset']}. Ground truth: {metrics['ground_truth']}.", "",
        f"Cities: {', '.join(metrics['cities'])}. Rows after cleaning: "
        f"{metrics['data']['row_counts_by_step']['geocoded']}.", "",
        "## Spatial-block CV (H3 res-7 cells held out), all errors in % of asking price", "",
        *header, *model_rows(metrics["models"]), "",
        "## Seen-locality CV (grouped by project proxy; localities usually seen, projects unseen)", "",
        *header, *model_rows(metrics["seen_locality"]["models"]), "",
        f"M+ vs B2 MdAPE difference: {significance['delta_mdape']:+.2f} points, 95% CI "
        f"[{significance['ci95'][0]:+.2f}, {significance['ci95'][1]:+.2f}] ({significance['method']}).", "",
        f"80% interval coverage: {coverage['overall']['coverage']:.1f}% overall, median width "
        f"{coverage['overall']['median_width_pct']:.1f}% of value. Per city: "
        + ", ".join(f"{c} {v['coverage']:.1f}%" for c, v in coverage["per_city"].items()) + ".", "",
        *[f"Routing operating point, {name}: " + (
            f"auto-accept when half-width <= {sel['grade_threshold']:.0f}%: {sel['auto_rate']:.1f}% of "
            f"cases, MdAPE {sel['mdape_auto']:.1f}%, over-valued >20% {sel['overval20_auto']:.1f}%."
            if sel["found"] else f"no threshold meets the rule ({sel['rule']}).")
          for name, sel in [("unseen H3 cell", selected),
                            ("seen locality", metrics["routing_curve_seen_locality"]["selected"])]], "",
        f"API latency p95: {metrics['latency']['p95_ms']:.0f} ms ({metrics['latency']['hardware']}).", "",
        "Not run: " + ", ".join(metrics["not_run"]) + " (reasons in metrics.json).",
    ]
    (config.RESULTS / "summary.md").write_text("\n".join(lines) + "\n", encoding="utf-8")


def main() -> None:
    logging.basicConfig(level=logging.INFO, format="%(asctime)s %(name)s %(message)s")
    logging.getLogger("httpx").setLevel(logging.WARNING)
    config.METRICS_PATH.unlink(missing_ok=True)
    ingest_listings.download()
    geocode.geocode_localities(clean.localities_to_geocode(clean.load_raw_listings()))
    poi_counts = ingest_osm.main()
    cleaning = clean.main()
    features.main()
    train.main()
    calibrate.main()
    route.main()
    explain.main()
    report.main()
    figures.main()
    bench_api.main()
    finalize_metrics(cleaning, poi_counts)
    write_summary(load_metrics())
    if "--skip-tests" not in sys.argv:
        subprocess.run([sys.executable, "-m", "pytest", "-q"], cwd=config.ROOT, check=True)


if __name__ == "__main__":
    main()
